"""Markdown tables for the README, rendered only from reports/*.json."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

SET_LABELS = {
    "gnhk_test_words": "GNHK test, words",
    "gnhk_test_lines": "GNHK test, lines",
    "canvas_heldout_fonts": "Canvas style, held-out fonts",
}


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def render_report(metrics: dict[str, Any] | None, baseline: dict[str, Any] | None) -> str:
    lines = ["<!-- Generated by `accuscan evaluate` / `accuscan baseline`. Do not edit. -->", ""]
    if metrics is None:
        lines.append("No trained model has been evaluated yet.")
        return "\n".join(lines) + "\n"
    lines += [
        "| Test set | Samples | CER (greedy) | WER (greedy) "
        "| CER (dictionary) | WER (dictionary) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for key, label in SET_LABELS.items():
        result = metrics["sets"].get(key)
        if not result:
            continue
        g = result["greedy"]
        d = result.get("dictionary", {})
        lines.append(
            f"| {label} | {g['samples']} | {_pct(g['cer'])} | {_pct(g['wer'])} | "
            f"{_pct(d.get('cer'))} | {_pct(d.get('wer'))} |"
        )
    gate = metrics["gate"]
    latency = metrics["latency_cpu"]
    lines += [
        "",
        f"Canvas gate: CER {_pct(gate['canvas_cer'])} against a {_pct(gate['threshold'])} bar, "
        f"so the demo opens in **{gate['defaultMode']}** mode.",
        "",
        f"Model file {latency['model_mb']} MB (int8). CPU latency per line, one thread: "
        + ", ".join(
            f"{v} ms at width {k.removeprefix('ms_width_')}"
            for k, v in latency.items()
            if k.startswith("ms_width_")
        )
        + ".",
    ]
    if baseline is not None:
        lines += [
            "",
            "| Model | Test set | Samples | CER | WER | Size | ms per crop (CPU) |",
            "|---|---|---:|---:|---:|---:|---:|",
        ]
        ours = metrics["sets"]
        for key in ("gnhk_test_words", "gnhk_test_lines"):
            mine = ours.get(key, {}).get("greedy")
            theirs = baseline["sets"].get(key)
            if mine:
                lines.append(
                    f"| AccuScan CRNN | {SET_LABELS[key]} | {mine['samples']} | "
                    f"{_pct(mine['cer'])} | "
                    f"{_pct(mine['wer'])} | {latency['model_mb']} MB | "
                    f"{latency.get('ms_width_256', 'n/a')} |"
                )
            if theirs:
                lines.append(
                    f"| {baseline['model']} | {SET_LABELS[key]} | {theirs['samples']} | "
                    f"{_pct(theirs['cer'])} | {_pct(theirs['wer'])} | {baseline['model_mb']} MB | "
                    f"{theirs['ms_per_crop']} |"
                )
    return "\n".join(lines) + "\n"


def _load(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def write_report(reports_dir: Path) -> Path:
    text = render_report(_load(reports_dir / "metrics.json"), _load(reports_dir / "baseline.json"))
    out = reports_dir / "metrics.md"
    out.write_text(text, encoding="utf-8")
    return out
